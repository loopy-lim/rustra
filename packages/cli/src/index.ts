interface GenerateOptions {
  schemaPath?: string;
  outputPath?: string;
  configPath?: string;
  cppOutputPath?: string;
  /** (P2) positional-facade.ts 추가 생성 — RN JSI invokeTyped 직접 호출 래퍼. */
  positional?: boolean;
  check?: boolean;
}

export async function runGenerate(args: string[], schemaOverride?: string): Promise<void> {
  const options = parseGenerateArgs(args);
  // --check도 생성기 구현과 함께 판정되어야 하므로 stale dist를 그대로
  // 사용하지 않는다. source entry로 실행 중이면 이미 최신 코드이므로
  // 자기 자신을 다시 빌드하지 않는다.
  autoRebuild();
  const { schemaPath, outputPath, cppOutputPath, positional, reactNativeScaffold, hostEntries } =
    resolvePaths(options, schemaOverride);
  const written = await generateFromSchema(
    schemaPath,
    outputPath,
    cppOutputPath,
    positional,
    reactNativeScaffold,
    hostEntries,
    options.check,
  );
  console.log(`${options.check ? 'Verified' : 'Generated'} TypeScript files in ${outputPath}:`);
  for (const f of written) console.log(`  ${f}`);
}

function resolvePaths(
  options: GenerateOptions,
  schemaOverride?: string,
): {
  schemaPath: string;
  outputPath: string;
  cppOutputPath?: string;
  positional?: boolean;
  reactNativeScaffold?: ReactNativeScaffoldOptions;
  hostEntries?: HostEntries;
} {
  let schemaPath: string;
  let outputPath: string;
  let config: RustraConfig | undefined;

  if (options.configPath) {
    config = readConfigSync(options.configPath);
    schemaPath = resolve(dirname(options.configPath), config.schema);
    outputPath = resolve(dirname(options.configPath), config.output);
  } else if (options.schemaPath && options.outputPath) {
    schemaPath = options.schemaPath;
    outputPath = options.outputPath;
  } else {
    console.error('Error: Provide --schema and --output, or --config with a config file.');
    process.exit(1);
  }

  if (schemaOverride) schemaPath = schemaOverride;

  const reactNativeScaffold = config?.reactNative
    ? resolveReactNativeScaffold(config, options.configPath!)
    : undefined;
  const cppOutputPath = options.cppOutputPath
    ? resolve(options.cppOutputPath)
    : config?.cppOutput
      ? resolve(dirname(options.configPath!), config.cppOutput)
      : reactNativeScaffold?.cppOutputPath;
  const resolvedOutputPath = resolve(outputPath);
  const hostEntries = config
    ? resolveHostEntries(config, options.configPath!, resolvedOutputPath)
    : undefined;

  return {
    schemaPath: resolve(schemaPath),
    outputPath: resolvedOutputPath,
    cppOutputPath,
    positional: options.positional ?? config?.positional,
    reactNativeScaffold: reactNativeScaffold
      ? { ...reactNativeScaffold, cppOutputPath: cppOutputPath! }
      : undefined,
    hostEntries,
  };
}

async function runWatch(args: string[]): Promise<void> {
  const options = parseGenerateArgs(args);
  const { schemaPath, outputPath, cppOutputPath, positional, reactNativeScaffold, hostEntries } =
    resolvePaths(options);

  await generateFromSchema(
    schemaPath,
    outputPath,
    cppOutputPath,
    positional,
    reactNativeScaffold,
    hostEntries,
  );
  console.log(`\nWatching ${schemaPath} for changes...`);

  let debounceTimer: ReturnType<typeof setTimeout> | null = null;
  watch(dirname(schemaPath), (_event, filename) => {
    if (!filename || !filename.endsWith('.json')) return;
    if (debounceTimer) clearTimeout(debounceTimer);
    debounceTimer = setTimeout(async () => {
      try {
        await generateFromSchema(
          schemaPath,
          outputPath,
          cppOutputPath,
          positional,
          reactNativeScaffold,
          hostEntries,
        );
        console.log(`[${new Date().toLocaleTimeString()}] Regenerated`);
      } catch (error) {
        console.error(`Regeneration failed: ${error instanceof Error ? error.message : error}`);
      }
    }, 100);
  });
}

async function generateFromSchema(
  schemaPath: string,
  outputPath: string,
  cppOutputPath?: string,
  positional = false,
  reactNativeScaffold?: ReactNativeScaffoldOptions,
  hostEntries?: HostEntries,
  check = false,
): Promise<string[]> {
  const schemaContent = await readFile(schemaPath, 'utf-8');
  const schema: PackageSchema = parsePackageSchema(JSON.parse(schemaContent));

  // 필드 순서 일관성 경고 — properties 가 알파벳 순으로 정렬돼 있으면 postcard
  // 선언 순서 가정이 깨질 가능성이 있다(과거 schemars 비-preserve_order 산출물).
  // 단순 우연 정렬(calculator 의 a,b 같은 짧은 세트)은 흔하므로, 스키마 전체에서
  // 정렬 징후가 반복될 때(≥3개 명령) 한 번만 요약 경고를 낸다.
  if (schema.fieldOrder !== 'declaration') {
    let sortedFieldSuspects = 0;
    for (const command of schema.commands) {
      for (const s of [command.inputSchema, command.outputSchema]) {
        const names = Object.keys(s.properties ?? {});
        const sorted = [...names].sort();
        if (names.length > 1 && JSON.stringify(names) === JSON.stringify(sorted)) {
          sortedFieldSuspects++;
        }
      }
    }
    if (sortedFieldSuspects >= 3) {
      console.warn(
        `[rustra] WARN: ${sortedFieldSuspects} field sets appear alphabetically sorted and ` +
          `the schema has no fieldOrder=declaration guarantee; postcard encodes in Rust ` +
          `declaration order — regenerate with current rustra or verify field order manually.`,
      );
    }
  }

  const files: GeneratedFile[] = [];
  const addFile = (targetDir: string, name: string, content: string) => {
    const path = resolve(targetDir, name);
    files.push({ path, content });
  };

  addFile(outputPath, 'types.ts', generateTypesTs(schema));
  addFile(outputPath, 'commands.ts', generateCommandsTs(schema));
  addFile(outputPath, 'contract.ts', generateContractTs(schemaContent));
  addFile(outputPath, 'rkyv-codecs.ts', generateRkyvCodecsTs(schema));
  addFile(outputPath, 'rkyv-registry.ts', generateRkyvRegistryTs(schema));

  // (이벤트 계약) 선언된 이벤트가 있을 때만 events.ts 를 만든다 — 없으면
  // 산출물 목록이 기존과 동일(하위호환).
  const eventsTs = generateEventsTs(schema);
  if (eventsTs) {
    addFile(outputPath, 'events.ts', eventsTs);
  }

  if (positional) {
    addFile(outputPath, 'positional-facade.ts', generatePositionalFacadeTs(schema));
  }

  if (reactNativeScaffold) {
    addFile(outputPath, 'react-native.ts', generateReactNativeEntryTs());
  }
  if (hostEntries?.node) {
    addFile(outputPath, 'node.ts', generateNodeEntryTs(hostEntries.node));
  }
  if (hostEntries?.bun) {
    addFile(outputPath, 'bun.ts', generateBunEntryTs(hostEntries.bun));
  }
  if (hostEntries?.tauri) {
    addFile(outputPath, 'tauri.ts', generateTauriEntryTs());
  }

  if (cppOutputPath) {
    addFile(cppOutputPath, 'rustra-generated-codecs.hpp', generateRkyvCodecsHpp(schema));
    addFile(cppOutputPath, 'rustra-generated-codecs.cpp', generateRkyvCodecsCpp(schema));
  }

  if (reactNativeScaffold) {
    for (const [name, content] of Object.entries(renderReactNativeModule(reactNativeScaffold))) {
      addFile(reactNativeScaffold.moduleDir, name, content);
    }
  }

  const written: string[] = [];
  for (const { path: filePath, content } of files) {
    let existing: string | null = null;
    try {
      existing = await readFile(filePath, 'utf-8');
    } catch {
      /* file doesn't exist */
    }
    if (existing === content) {
      const relativePath = manifestPathFor(outputPath, filePath);
      written.push(`${relativePath} (unchanged)`);
    } else {
      if (!check) {
        await mkdir(dirname(filePath), { recursive: true });
        await writeFile(filePath, content);
      }
      written.push(
        check
          ? `${manifestPathFor(outputPath, filePath)} (drift)`
          : existing !== null
            ? `${manifestPathFor(outputPath, filePath)} (updated)`
            : manifestPathFor(outputPath, filePath),
      );
    }
  }

  const manifestPath = resolve(outputPath, '.rustra-generated.json');
  if (check) {
    await checkGeneratedFiles(
      files.map((file) => ({ path: file.path, content: file.content })),
      manifestPath,
      { schemaContent, generatorVersion: cliVersion },
    );
    return written;
  }

  if (reactNativeScaffold) {
    await ensureReactNativeDependency(
      reactNativeScaffold.appRoot,
      reactNativeScaffold.moduleDir,
      reactNativeScaffold.adapterRange,
    );
  }
  if (hostEntries) {
    await ensureHostDependencies(hostEntries);
  }
  await writeFile(
    manifestPath,
    `${JSON.stringify(
      buildGeneratedManifest(
        schemaContent,
        cliVersion,
        files.map((file) => ({
          path: manifestPathFor(outputPath, file.path),
          content: file.content,
        })),
      ),
      null,
      2,
    )}\n`,
  );
  return written;
}

/**
 * Auto-rebuild the CLI if source files are newer than dist.
 * Prevents running a stale binary that generates outdated code.
 */
function collectFileMtimes(
  directory: string,
  suffix: string,
  root = directory,
  result = new Map<string, number>(),
): Map<string, number> {
  if (!existsSync(directory)) return result;
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (
      entry.name === 'node_modules' ||
      entry.name.endsWith('.test.ts') ||
      entry.name.endsWith('.spec.ts')
    )
      continue;
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) {
      collectFileMtimes(path, suffix, root, result);
    } else if (entry.name.endsWith(suffix)) {
      result.set(relative(root, path), statSync(path).mtimeMs);
    }
  }
  return result;
}

function autoRebuild(): void {
  try {
    const modulePath = fileURLToPath(import.meta.url);
    if (toPosixPath(modulePath).includes('/src/')) return;
    const cliDir = resolve(dirname(modulePath), '..');
    const srcDir = resolve(cliDir, 'src');
    const distDir = resolve(cliDir, 'dist');

    const sourceFiles = collectFileMtimes(srcDir, '.ts');
    const distFiles = collectFileMtimes(distDir, '.js');
    const stale = [...sourceFiles].some(([sourcePath, sourceMtime]) => {
      const distPath = `${sourcePath.slice(0, -'.ts'.length)}.js`;
      const distMtime = distFiles.get(distPath);
      return distMtime === undefined || sourceMtime > distMtime;
    });

    if (stale) {
      console.log('CLI source is newer than dist — rebuilding...');
      execSync('bun run build', { cwd: cliDir, stdio: 'pipe' });
      console.log('CLI rebuilt.');
    }
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    throw new Error(`CLI auto-rebuild failed: ${message}`, { cause: error });
  }
}

function parseGenerateArgs(args: string[]): GenerateOptions {
  const options: GenerateOptions = {};

  for (let i = 0; i < args.length; i++) {
    switch (args[i]) {
      case '--schema':
        options.schemaPath = args[++i];
        break;
      case '--output':
        options.outputPath = args[++i];
        break;
      case '--cpp-output':
        options.cppOutputPath = args[++i];
        break;
      case '--config':
        options.configPath = args[++i];
        break;
      case '--positional':
        options.positional = true;
        break;
      case '--check':
        options.check = true;
        break;
    }
  }

  return options;
}

type CargoMetadata = {
  target_directory?: string;
  packages: Array<{
    name: string;
    manifest_path: string;
    targets: Array<{
      name: string;
      crate_types: string[];
      kind?: string[];
    }>;
  }>;
};

const cargoMetadataCache = new Map<
  string,
  { mtimeMs: number; size: number; metadata: CargoMetadata }
>();

export function resolveCodegenTarget(
  configPath: string,
  config: RustraConfig,
): { manifestPath: string; packageName: string; binaryName: string; cwd: string } {
  const cwd = dirname(resolve(configPath));
  const manifestPath = config.codegen?.rustManifest
    ? resolve(cwd, config.codegen.rustManifest)
    : findCargoManifest(cwd);
  if (!manifestPath) {
    throw new Error('codegen.rust_manifest_missing: set codegen.rustManifest in rustra.json');
  }
  const metadata = readCargoMetadata(manifestPath);
  const candidates = cargoPackagesForManifest(
    metadata.packages,
    manifestPath,
    config.codegen?.rustPackage,
  );
  if (candidates.length !== 1) {
    const names =
      candidates
        .map((candidate) => candidate.name)
        .sort()
        .join(', ') || 'none';
    throw new Error(`codegen.rust_package_ambiguous: found ${names}; set codegen.rustPackage`);
  }
  const packageInfo = candidates[0]!;
  return {
    manifestPath: resolve(manifestPath),
    packageName: packageInfo.name,
    binaryName: selectCodegenBinary(packageInfo.targets, config.codegen?.rustBinary),
    cwd,
  };
}

type HostEntries = {
  appRoot: string;
  node?: CargoHostEntry & { args?: string[] };
  bun?: CargoHostEntry;
  tauri?: true;
};

export function selectReactNativeCargoTarget(
  metadata: CargoMetadata,
  manifestPath: string,
  requestedPackage?: string,
): { rustPackage: string; rustLibrary: string } {
  const manifest = resolve(manifestPath);
  const manifestPackages = cargoPackagesForManifest(metadata.packages, manifestPath);
  const candidates = requestedPackage
    ? metadata.packages.filter((candidate) => candidate.name === requestedPackage)
    : manifestPackages.length > 0
      ? manifestPackages
      : metadata.packages.filter((candidate) =>
          candidate.targets.some((target) => target.crate_types.includes('staticlib')),
        );

  if (candidates.length !== 1) {
    const names =
      candidates
        .map((candidate) => candidate.name)
        .sort()
        .join(', ') || 'none';
    throw new Error(
      requestedPackage
        ? `Cargo package ${requestedPackage} was not found uniquely in ${manifestPath}`
        : `React Native setup found ${candidates.length} static-library crates (${names}). ` +
            'Point rustManifest at the app crate, or set reactNative.rustPackage.',
    );
  }

  const selected = candidates[0]!;
  const staticLibraries = selected.targets.filter((target) =>
    target.crate_types.includes('staticlib'),
  );
  if (staticLibraries.length !== 1) {
    throw new Error(
      `Cargo package ${selected.name} must expose exactly one staticlib target. ` +
        'Add crate-type = ["rlib", "staticlib"] under [lib].',
    );
  }
  return { rustPackage: selected.name, rustLibrary: staticLibraries[0]!.name };
}

function readCargoMetadata(manifestPath: string): CargoMetadata {
  try {
    const CARGO_TOML = realpathSync(resolve(manifestPath));
    const manifestStat = statSync(CARGO_TOML);
    if (basename(CARGO_TOML) !== 'Cargo.toml' || !manifestStat.isFile()) {
      throw new Error('rustManifest must point to a regular Cargo.toml file');
    }
    const cached = cargoMetadataCache.get(CARGO_TOML);
    if (cached && cached.mtimeMs === manifestStat.mtimeMs && cached.size === manifestStat.size) {
      return cached.metadata;
    }
    const CARGO_METADATA_ARGS = [
      'metadata',
      '--format-version',
      '1',
      '--no-deps',
      '--manifest-path',
      CARGO_TOML,
    ];
    const cargoOutput = execFileSync('cargo', CARGO_METADATA_ARGS, { encoding: 'utf8' });
    const metadata = JSON.parse(cargoOutput) as CargoMetadata;
    cargoMetadataCache.set(CARGO_TOML, {
      mtimeMs: manifestStat.mtimeMs,
      size: manifestStat.size,
      metadata,
    });
    return metadata;
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    throw new Error(`Could not inspect ${manifestPath} with cargo metadata: ${message}`, {
      cause: error,
    });
  }
}

function readCargoTarget(manifestPath: string, requestedPackage?: string) {
  const metadata = readCargoMetadata(manifestPath);
  return selectReactNativeCargoTarget(metadata, manifestPath, requestedPackage);
}

function selectHostPackage(
  metadata: CargoMetadata,
  manifestPath: string,
  requestedPackage: string | undefined,
) {
  const candidates = cargoPackagesForManifest(metadata.packages, manifestPath, requestedPackage);
  if (candidates.length !== 1) {
    const names =
      candidates
        .map((candidate) => candidate.name)
        .sort()
        .join(', ') || 'none';
    throw new Error(
      requestedPackage
        ? `Cargo package ${requestedPackage} was not found uniquely in ${manifestPath}`
        : `Host setup found ${candidates.length} Cargo packages (${names}). ` +
            'Point rustManifest at the app crate, or set the host rustPackage.',
    );
  }
  return candidates[0]!;
}

function requireTargetDirectory(metadata: CargoMetadata): string {
  if (!metadata.target_directory) {
    throw new Error('cargo metadata did not return target_directory');
  }
  return resolve(metadata.target_directory);
}

function resolveHostEntries(
  config: RustraConfig,
  configPath: string,
  outputPath: string,
): HostEntries | undefined {
  if (!config.node && !config.bun && !config.tauri) return undefined;
  const appRoot = dirname(resolve(configPath));
  const entries: HostEntries = { appRoot };

  if (config.node) {
    const manifest = config.node.rustManifest
      ? resolve(appRoot, config.node.rustManifest)
      : findCargoManifest(appRoot);
    if (!manifest) {
      throw new Error('Node setup could not find Cargo.toml. Set node.rustManifest.');
    }
    const metadata = readCargoMetadata(manifest);
    const cargoPackage = selectHostPackage(metadata, manifest, config.node.rustPackage);
    const binaries = cargoPackage.targets.filter(
      (target) => target.kind?.includes('bin') || target.crate_types.includes('bin'),
    );
    const selectedName = selectCodegenBinary(binaries, config.node.rustBinary, [
      cargoPackage.name,
      'generate',
    ]);
    const selected = binaries.find((target) => target.name === selectedName)!;
    entries.node = {
      targetDirectoryUrl: `${portablePackagePath(outputPath, requireTargetDirectory(metadata))}/`,
      targetName: selected.name,
      args: config.node.args,
    };
  }

  if (config.bun) {
    const manifest = config.bun.rustManifest
      ? resolve(appRoot, config.bun.rustManifest)
      : findCargoManifest(appRoot);
    if (!manifest) {
      throw new Error('Bun setup could not find Cargo.toml. Set bun.rustManifest.');
    }
    const metadata = readCargoMetadata(manifest);
    const cargoPackage = selectHostPackage(metadata, manifest, config.bun.rustPackage);
    const libraries = cargoPackage.targets.filter((target) =>
      target.crate_types.includes('cdylib'),
    );
    const selected = config.bun.rustLibrary
      ? libraries.find((target) => target.name === config.bun!.rustLibrary)
      : libraries.length === 1
        ? libraries[0]
        : undefined;
    if (!selected) {
      throw new Error(
        `Bun setup requires one Cargo cdylib (${libraries
          .map((target) => target.name)
          .sort()
          .join(', ')}). Add crate-type = ["rlib", "cdylib"], or set bun.rustLibrary.`,
      );
    }
    entries.bun = {
      targetDirectoryUrl: `${portablePackagePath(outputPath, requireTargetDirectory(metadata))}/`,
      targetName: selected.name,
    };
  }

  if (config.tauri) entries.tauri = true;
  return entries;
}

function resolveReactNativeScaffold(
  config: RustraConfig,
  configPath: string,
): ReactNativeScaffoldOptions {
  const rn = config.reactNative!;
  const appRoot = dirname(resolve(configPath));
  const moduleDir = resolve(appRoot, rn.moduleDir ?? 'modules/rustra-bridge');
  if (moduleDir !== appRoot && !moduleDir.startsWith(`${appRoot}/`)) {
    throw new Error('Config reactNative.moduleDir must stay inside the app directory');
  }
  const rustManifestPath = rn.rustManifest
    ? resolve(appRoot, rn.rustManifest)
    : findCargoManifest(appRoot);
  if (!rustManifestPath) {
    throw new Error(
      'React Native setup could not find Cargo.toml. Set reactNative.rustManifest in rustra.json.',
    );
  }
  const inferred = readCargoTarget(rustManifestPath, rn.rustPackage);
  const rustPackage = inferred.rustPackage;
  const rustLibrary = rn.rustLibrary ?? inferred.rustLibrary;
  return {
    appRoot,
    moduleDir,
    cppOutputPath: config.cppOutput
      ? resolve(appRoot, config.cppOutput)
      : resolve(moduleDir, 'generated'),
    rustManifestPath,
    rustPackage,
    rustLibrary,
    adapterRange: cliManifest.rustraTemplate.reactNativeRange,
    legacyBenchmarks: rn.legacyBenchmarks,
  };
}

async function ensureReactNativeDependency(
  appRoot: string,
  moduleDir: string,
  adapterRange: string,
): Promise<void> {
  const manifestPath = resolve(appRoot, 'package.json');
  let raw: string;
  try {
    raw = await readFile(manifestPath, 'utf8');
  } catch {
    throw new Error(
      'React Native setup requires package.json next to rustra.json so autolinking can see the generated module.',
    );
  }
  const manifest = JSON.parse(raw) as Record<string, unknown> & {
    dependencies?: Record<string, string>;
    devDependencies?: Record<string, string>;
    workspaces?: string[];
  };
  const dependencies = { ...(manifest.dependencies ?? {}) };
  const modulePath = portablePackagePath(appRoot, moduleDir);
  const workspacePath = modulePath.replace(/^\.\//, '');
  const expectedModule = 'workspace:*';
  const previousGeneratedModule = `file:${modulePath}`;
  const existingModule = dependencies[GENERATED_REACT_NATIVE_PACKAGE];
  if (
    existingModule !== undefined &&
    existingModule !== expectedModule &&
    existingModule !== previousGeneratedModule
  ) {
    throw new Error(
      `Dependency ${GENERATED_REACT_NATIVE_PACKAGE} already points to ${existingModule}; ` +
        `refusing to replace it with the generated workspace at ${workspacePath}.`,
    );
  }
  dependencies[GENERATED_REACT_NATIVE_PACKAGE] = expectedModule;
  if (
    dependencies['@rustra/react-native'] === undefined &&
    manifest.devDependencies?.['@rustra/react-native'] === undefined
  ) {
    dependencies['@rustra/react-native'] = adapterRange;
  }
  manifest.dependencies = Object.fromEntries(
    Object.entries(dependencies).sort(([a], [b]) => a.localeCompare(b)),
  );
  const workspaces = manifest.workspaces ?? [];
  if (!Array.isArray(workspaces) || workspaces.some((entry) => typeof entry !== 'string')) {
    throw new Error('React Native setup requires package.json workspaces to be a string array');
  }
  if (!workspaces.includes(workspacePath)) {
    manifest.workspaces = [...workspaces, workspacePath].sort();
  }
  const next = `${JSON.stringify(manifest, null, 2)}\n`;
  if (next !== raw) await writeFile(manifestPath, next);
}

async function ensureHostDependencies(hosts: HostEntries): Promise<void> {
  const manifestPath = resolve(hosts.appRoot, 'package.json');
  let raw: string;
  try {
    raw = await readFile(manifestPath, 'utf8');
  } catch {
    throw new Error('Node, Bun, and Tauri setup requires package.json next to rustra.json.');
  }
  const manifest = JSON.parse(raw) as Record<string, unknown> & {
    dependencies?: Record<string, string>;
    devDependencies?: Record<string, string>;
  };
  const dependencies = { ...(manifest.dependencies ?? {}) };
  const required = [
    '@rustra/types',
    ...(hosts.node ? ['@rustra/node'] : []),
    ...(hosts.bun ? ['@rustra/bun'] : []),
    ...(hosts.tauri ? ['@rustra/tauri'] : []),
  ];
  const expected = `^${cliVersion}`;
  for (const name of required) {
    const existing = dependencies[name] ?? manifest.devDependencies?.[name];
    if (
      existing !== undefined &&
      existing !== expected &&
      !existing.startsWith('file:') &&
      !existing.startsWith('workspace:')
    ) {
      throw new Error(
        `Dependency ${name} already points to ${existing}; refusing to replace it with ${expected}. ` +
          'Align the Rustra release line explicitly.',
      );
    }
    if (existing === undefined) dependencies[name] = expected;
  }
  manifest.dependencies = Object.fromEntries(
    Object.entries(dependencies).sort(([a], [b]) => a.localeCompare(b)),
  );
  const next = `${JSON.stringify(manifest, null, 2)}\n`;
  if (next !== raw) await writeFile(manifestPath, next);
}

function portablePackagePath(from: string, to: string): string {
  const path = toPosixPath(relative(from, to));
  return path.startsWith('.') ? path : `./${path}`;
}

function parsePackageSchema(value: unknown): PackageSchema {
  if (typeof value !== 'object' || value === null) {
    throw new Error('Invalid schema: expected an object');
  }
  const obj = value as Record<string, unknown>;
  if (typeof obj.packageId !== 'string') {
    throw new Error('Invalid schema: missing or invalid "packageId"');
  }
  if (!Array.isArray(obj.commands)) {
    throw new Error('Invalid schema: missing or invalid "commands" array');
  }
  if (obj.fieldOrder !== undefined && obj.fieldOrder !== 'declaration') {
    throw new Error('Invalid schema: "fieldOrder" must be "declaration" when provided');
  }
  for (let i = 0; i < obj.commands.length; i++) {
    const cmd = obj.commands[i] as Record<string, unknown>;
    if (typeof cmd.name !== 'string') {
      throw new Error(`Invalid schema: commands[${i}].name must be a string`);
    }
    if (typeof cmd.inputType !== 'string' || typeof cmd.outputType !== 'string') {
      throw new Error(`Invalid schema: commands[${i}] must have inputType and outputType`);
    }
    if (typeof cmd.inputSchema !== 'object' || typeof cmd.outputSchema !== 'object') {
      throw new Error(`Invalid schema: commands[${i}] must have inputSchema and outputSchema`);
    }
    // 식별자 화이트리스트 — name/inputType/outputType/definitions 키는 생성 TS 에
    // 그대로 삽입되므로 변조 schema.json 통한 코드 주입을 차단한다.
    // '()' 은 unit 타입 센티넬(generate.ts 의 `command.inputType !== '()'` 와 동일).
    assertIdentifier(cmd.name, `commands[${i}].name`);
    if (cmd.inputType !== '()') {
      assertIdentifier(cmd.inputType, `commands[${i}].inputType`);
    }
    if (cmd.outputType !== '()') {
      assertIdentifier(cmd.outputType, `commands[${i}].outputType`);
    }
    if (cmd.definitions) {
      for (const key of Object.keys(cmd.definitions)) {
        assertIdentifier(key, `commands[${i}].definitions key`);
      }
    }
    // 중첩 definitions 키 / 속성명 / $ref 대상도 재귀 검증 — collectDefinitionsInner
    // 가 수집하는 모든 정의와 tsObjectFromSchema 가 무인용 방출하는 모든 필드명.
    assertSchemaIdentifiers(cmd.inputSchema, `commands[${i}].inputSchema`);
    assertSchemaIdentifiers(cmd.outputSchema, `commands[${i}].outputSchema`);
    if (cmd.definitions) {
      for (const [key, def] of Object.entries(cmd.definitions)) {
        assertSchemaIdentifiers(def, `commands[${i}].definitions.${key}`);
      }
    }
  }
  return value as PackageSchema;
}

