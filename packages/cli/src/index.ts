/** TS 식별자로 안전한 문자열만 허용 — 생성 코드에 그대로 삽입되는 이름의
 * 주입 방어. $ 허용은 JS 식별자 규격 준수. */
const TS_IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function assertIdentifier(value: string, where: string): void {
  if (!TS_IDENTIFIER.test(value)) {
    throw new Error(
      `Invalid schema: ${where} must be a plain identifier, got: ${JSON.stringify(value)}`,
    );
  }
}

/**
 * 스키마 트리 전체의 식별자 화이트리스트 — 코드젠이 식별자 위치(따옴표 없이
 * 방출하는 이름)에 삽입하는 모든 키를 검증한다:
 * - `definitions` 키(최상위 cmd.definitions 외에 inputSchema/outputSchema 내부,
 *   다른 definition 내부의 중첩 definitions 포함 — collectDefinitionsInner 가
 *   재귀 수집해 `export type ${name}` 으로 방출)
 * - `properties` 키(생성 TS 멤버 `${name}:`, rkyv 코덱 `args.${name}`,
 *   C++ `getProperty(rt, "${name}")` — 모두 무인용 방출)
 * - `$ref` 대상 타입명(resolveRef 로 벗겨 타입 위치에 방출)
 *
 * schemars/serde 는 Rust 필드명(식별자)만 내보내므로 정상 스키마는 영향 없다.
 * description/enum 값 등 자유 문자열은 여기서 거부하지 않는다 — 방출 시점
 * 이스케이프(codegen.ts escapeJsDoc/escapeStringLiteral)로 방어한다.
 */
function assertSchemaIdentifiers(
  schema: unknown,
  where: string,
  visited: Set<unknown> = new Set(),
): void {
  if (typeof schema !== 'object' || schema === null || visited.has(schema)) return;
  visited.add(schema);
  const node = schema as {
    definitions?: Record<string, unknown>;
    properties?: Record<string, unknown>;
    $ref?: unknown;
    [key: string]: unknown;
  };
  if (typeof node.$ref === 'string') {
    const target = node.$ref.replace(/^#\/(definitions\/|\$defs\/)/, '');
    assertIdentifier(target, `${where} $ref target`);
  }
  if (node.definitions) {
    for (const key of Object.keys(node.definitions)) {
      assertIdentifier(key, `${where} definitions key`);
      assertSchemaIdentifiers(node.definitions[key], `${where}.${key}`, visited);
    }
  }
  if (node.properties) {
    for (const key of Object.keys(node.properties)) {
      assertIdentifier(key, `${where} property name`);
      assertSchemaIdentifiers(node.properties[key], `${where}.${key}`, visited);
    }
  }
  // collectDefinitionsInner 의 순회와 동일한 하위 스키마 위치을 따라간다.
  for (const arrayKey of ['anyOf', 'oneOf', 'allOf', 'prefixItems'] as const) {
    const arr = node[arrayKey];
    if (Array.isArray(arr)) {
      for (let i = 0; i < arr.length; i++) {
        assertSchemaIdentifiers(arr[i], `${where}.${arrayKey}[${i}]`, visited);
      }
    }
  }
  const items = node.items;
  if (Array.isArray(items)) {
    items.forEach((s, i) => assertSchemaIdentifiers(s, `${where}.items[${i}]`, visited));
  } else if (items) {
    assertSchemaIdentifiers(items, `${where}.items`, visited);
  }
  if (
    node.additionalProperties &&
    typeof node.additionalProperties === 'object' &&
    !Array.isArray(node.additionalProperties)
  ) {
    assertSchemaIdentifiers(node.additionalProperties, `${where}.additionalProperties`, visited);
  }
}

/** import 로 main() 이 실행되지 않도록 진입점 판별 — 테스트가 ./index.js 를
 * import 해도 CLI 가 실행되지 않는다. bin 스크립트(node dist/index.js)와
 * `node src/index.ts` 직접 실행 양쪽 모두 진입점으로 취급한다. */
function isCliEntry(): boolean {
  if (!process.argv[1]) return false;
  try {
    return realpathSync(resolve(process.argv[1])) === fileURLToPath(import.meta.url);
  } catch {
    return false;
  }
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);

  if (args.length === 0 || args[0] === '--help' || args[0] === '-h') {
    printHelp();
    process.exit(0);
  }

  if (args[0] === 'generate') {
    const rest = args.slice(1);
    if (rest.includes('--watch')) {
      await runWatch(rest.filter((a) => a !== '--watch'));
      return;
    }
    await runGenerate(rest);
    return;
  }

  if (args[0] === 'codegen') {
    await runCodegen(args.slice(1));
    return;
  }

  if (args[0] === 'init') {
    await runInit(args.slice(1));
    return;
  }

  if (args[0] === 'diff') {
    await runDiff(args.slice(1));
    return;
  }

  if (args[0] === 'doctor') {
    await runDoctor(args.slice(1));
    return;
  }

  if (args[0] === 'dev') {
    const { runDev } = await import('./dev.js');
    await runDev(args.slice(1));
    return;
  }

  console.error(`Unknown command: ${args[0]}`);
  console.error('Run "rustra --help" for usage information.');
  process.exit(1);
}

/** `rustra doctor [--config rustra.json] [--format text|json] [--strict]`. */
export async function runDoctor(args: string[]): Promise<void> {
  const options = parseDoctorArgs(args);
  const report = await collectDoctorReportAsync({
    configPath: resolve(options.configPath),
    strict: options.strict,
  });
  console.log(options.format === 'json' ? formatDoctorJson(report) : formatDoctorText(report));
  process.exitCode = doctorExitCode(report, options.strict);
}

interface CodegenOptions {
  configPath?: string;
  check?: boolean;
}

function parseCodegenArgs(args: string[]): CodegenOptions {
  const options: CodegenOptions = {};
  for (let index = 0; index < args.length; index += 1) {
    switch (args[index]) {
      case '--config':
        options.configPath = args[++index];
        break;
      case '--check':
        options.check = true;
        break;
      default:
        throw new Error(`Unknown codegen option: ${args[index]}`);
    }
  }
  if (!options.configPath) throw new Error('codegen requires --config <path>');
  return options;
}

export async function runCodegen(args: string[]): Promise<void> {
  const options = parseCodegenArgs(args);
  const configPath = resolve(options.configPath!);
  const config = readConfigSync(configPath);
  const target = resolveCodegenTarget(configPath, config);
  const manifestPath = resolve(dirname(configPath), config.output, '.rustra-generated.json');
  if (options.check && !existsSync(manifestPath)) {
    throw new Error(`Generated check requires ${manifestPath}; ` + 'run rustra codegen first');
  }
  console.log(
    `[rustra] Rust schema: cargo run --manifest-path ${target.manifestPath} ` +
      `--package ${target.packageName} --bin ${target.binaryName}`,
  );
  const checkRoot = options.check
    ? await mkdtemp(resolve(tmpdir(), 'rustra-codegen-check-'))
    : null;
  try {
    await spawnInherit(
      'cargo',
      [
        'run',
        '--quiet',
        '--manifest-path',
        target.manifestPath,
        '--package',
        target.packageName,
        '--bin',
        target.binaryName,
      ],
      target.cwd,
      checkRoot ? { env: { RUSTRA_SCHEMA_OUT: checkRoot } } : undefined,
    );
    if (checkRoot) {
      const temporarySchema = resolve(checkRoot, 'schema.json');
      if (!existsSync(temporarySchema)) {
        throw new Error(
          `Rust codegen did not produce ${temporarySchema}; ` +
            'the generator must honor RUSTRA_SCHEMA_OUT in check mode',
        );
      }
      console.log(`[rustra] TypeScript/C++: generate --config ${configPath} --check`);
      await runGenerate(['--config', configPath, '--check'], temporarySchema);
    }
  } finally {
    if (checkRoot) await rm(checkRoot, { recursive: true, force: true });
  }
  if (options.check) return;
  console.log(`[rustra] TypeScript/C++: generate --config ${configPath}`);
  await runGenerate(['--config', configPath]);
}

/**
 * `rustra diff --old a.json --new b.json [--format json]` — 스키마 버전 간
 * breaking change 검출. breaking 이 있으면 exit 1 (CI 게이트용).
 */
async function runDiff(args: string[]): Promise<void> {
  const getOpt = (name: string): string | undefined => {
    const i = args.indexOf(`--${name}`);
    return i >= 0 ? args[i + 1] : undefined;
  };
  const oldPath = getOpt('old');
  const newPath = getOpt('new');
  const asJson = args.includes('--format') && args[args.indexOf('--format') + 1] === 'json';

  if (!oldPath || !newPath) {
    console.error(
      'Error: --old and --new are required. Usage: rustra diff --old v1.json --new v2.json',
    );
    throw new Error('--old and --new are required. Usage: rustra diff --old v1.json --new v2.json');
  }

  const [oldRaw, newRaw] = await Promise.all([
    readFile(resolve(oldPath), 'utf-8'),
    readFile(resolve(newPath), 'utf-8'),
  ]);
  const result = diffSchemas(
    parsePackageSchema(JSON.parse(oldRaw)),
    parsePackageSchema(JSON.parse(newRaw)),
  );

  if (asJson) {
    console.log(JSON.stringify(result, null, 2));
  } else {
    console.log(formatDiffResult(result));
    if (result.compatible.length > 0) {
      console.log(`Compatible additions (${result.compatible.length}):`);
      for (const c of result.compatible) console.log(`  + ${c}`);
    }
  }

  if (result.breaking.length > 0) process.exitCode = 1;
}

/**
 * `rustra init <dir>` — 프로젝트 스캐폴딩.
 *
 * 최소 동작 구조를 생성한다: Cargo 크레이트(의존성은 버전 지정 — crates.io 발행 기준),
 * lib.rs 의 공유 패키지 정의, 실제 generate bin, package.json(codegen 스크립트),
 * rustra.json(CLI 설정)을 만든다.
 */
async function runInit(args: string[]): Promise<void> {
  const dir = args.find((a) => !a.startsWith('--'));
  if (!dir) {
    throw new Error('Provide a project directory. Usage: rustra init my-project');
  }
  const root = resolve(dir);
  const versions = templateVersions(
    cliVersion,
    cliManifest.dependencies['@rustra/types'],
    cliManifest.rustraTemplate.cargoRange,
  );
  const files = renderInitProjectFiles(versions);

  await mkdir(resolve(root, 'src/bin'), { recursive: true });
  await writeFile(resolve(root, 'Cargo.toml'), files.cargoToml);
  await writeFile(resolve(root, 'src/lib.rs'), files.libRs);
  await writeFile(resolve(root, 'src/main.rs'), files.mainRs);
  await writeFile(resolve(root, 'src/bin/generate.rs'), files.generateRs);
  await writeFile(resolve(root, 'package.json'), files.packageJson);
  await writeFile(resolve(root, 'rustra.json'), files.rustraJson);

  console.log(`Created rustra project in ${root}:`);
  console.log(
    '  Cargo.toml, src/lib.rs, src/main.rs, src/bin/generate.rs, package.json, rustra.json',
  );
  console.log('\nNext steps:');
  console.log('  cd ' + dir);
  console.log('  bun install');
  console.log('  bun run codegen      # schema + complete TS client');
  console.log('  cargo run            # invokes the generated echo command');
}

